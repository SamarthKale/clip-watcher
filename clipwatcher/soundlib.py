# ---------------------------------------------------------------- music
def _kick(gain: float = 1.0) -> list[float]:
    n = int(0.35 * SR)
    return [s * gain for s in drive(mul(osc(lambda i: 45 + 100 * math.exp(-i / (0.03 * SR)), n),
                                         env_exp(n, 0.12)), 1.5)]


def _snare(seed: int) -> list[float]:
    n = int(0.25 * SR)
    nz = mul(highpass(noise(n, seed), 1200), env_exp(n, 0.07))
    body = mul(osc(190, n), env_exp(n, 0.05))
    return [a + 0.5 * c for a, c in zip(nz, body)]


def _hat(seed: int, open_: bool = False) -> list[float]:
    n = int((0.25 if open_ else 0.05) * SR)
    return mul(highpass(noise(n, seed), 7000), env_exp(n, 0.08 if open_ else 0.015))


def _pad(notes: list[int], dur: float) -> tuple[list[float], list[float]]:
    n = int(dur * SR)
    left = [0.0] * n
    right = [0.0] * n
    e = env_adsr(n, 0.25, 0.4, 0.75, 0.5)
    for k, m in enumerate(notes):
        for det, side in ((-0.06, left), (0.06, right)):
            x = osc(midi(m + det), n, "tri", phase=0.17 * k)
            for i in range(n):
                side[i] += x[i] * e[i]
    return lowpass(left, 1800), lowpass(right, 1800)


def music_lofi() -> Buf:
    bpm, bars = 84, 8
    beat = 60 / bpm
    b = Buf(bars * 4 * beat, loop=True)
    prog = [[57, 60, 64, 67], [53, 57, 60, 64], [48, 52, 55, 59], [55, 59, 62, 65]]  # Am7 Fmaj7 Cmaj7 G7
    for bar in range(bars):
        t0 = bar * 4 * beat
        lp, rp = _pad(prog[bar % 4], 4 * beat)
        b.add(t0, lp, pan=-0.5, gain=0.16)
        b.add(t0, rp, pan=0.5, gain=0.16)
        bass_n = int(1.8 * beat * SR)
        root = prog[bar % 4][0] - 24
        b.add(t0, mul(osc(midi(root), bass_n), env_adsr(bass_n, 0.01, 0.2, 0.6, 0.2)), gain=0.32)
        b.add(t0 + 2.5 * beat, mul(osc(midi(root + 7), int(beat * SR)), env_exp(int(beat * SR), 0.3)), gain=0.22)
        for q in range(4):
            if q in (0, 2):
                b.add(t0 + q * beat, _kick(), gain=0.5)
            if q in (1, 3):
                b.add(t0 + q * beat + 0.02, lowpass(_snare(bar * 4 + q), 3500), gain=0.25)
            for h in (0, 0.5):
                swing = 0.08 * beat if h else 0
                b.add(t0 + (q + h) * beat + swing, _hat(bar * 8 + q * 2 + int(h * 2)), gain=0.10, pan=0.3)
    # vinyl crackle
    r = _rng(21)
    for _ in range(int(b.n / SR * 9)):
        b.add(r.uniform(0, b.n / SR), mul(noise(80, r.randint(0, 9999)), env_exp(80, 0.0005)), gain=0.05,
              pan=r.uniform(-1, 1))
    b.scale_rms(-20)
    return b


def music_tension() -> Buf:
    bpm, bars = 70, 6
    beat = 60 / bpm
    dur = bars * 4 * beat
    b = Buf(dur, loop=True)
    n = b.n
    lfo = [0.6 + 0.4 * math.sin(2 * math.pi * i / n * 3) for i in range(n)]
    for m, pan, g in ((33, -0.4, 0.5), (40, 0.4, 0.35), (45, 0.0, 0.18)):
        x = lowpass(osc(midi(m), n, "saw"), 260)
        b.add(0, mul(x, lfo), pan=pan, gain=g)
    for q in range(bars * 4):
        b.add(q * beat, _hat(300 + q), gain=0.12, pan=0.5)
        b.add(q * beat, _kick(0.6), gain=0.35 if q % 2 == 0 else 0.15)
    for k in range(bars // 2):
        hn = int(2.5 * SR)
        b.add(k * 8 * beat, mul(osc(lambda i: 40 + 60 * math.exp(-i / (0.08 * SR)), hn), env_exp(hn, 0.8)), gain=0.4)
    b.scale_rms(-20)
    return b


def music_upbeat() -> Buf:
    bpm, bars = 112, 8
    beat = 60 / bpm
    b = Buf(bars * 4 * beat, loop=True)
    prog = [[60, 64, 67], [57, 60, 64], [65, 69, 72], [67, 71, 74]]  # C Am F G
    bass_pat = [0, 0, 7, 0, 12, 0, 7, 5]
    for bar in range(bars):
        t0 = bar * 4 * beat
        chord = prog[bar % 4]
        for e8 in range(8):
            t = t0 + e8 * beat / 2
            bn = int(0.22 * SR)
            b.add(t, lowpass(mul(osc(midi(chord[0] - 24 + bass_pat[e8]), bn, "saw"), env_exp(bn, 0.08)), 900),
                  gain=0.3)
            if e8 in (1, 3, 5, 7):  # off-beat chord stabs
                sn = int(0.18 * SR)
                for k, m in enumerate(chord):
                    b.add(t, lowpass(mul(osc(midi(m + 12), sn, "square"), env_exp(sn, 0.05)), 2500),
                          pan=-0.4 + 0.4 * k, gain=0.06)
            b.add(t, _hat(bar * 16 + e8), gain=0.12, pan=0.35)
        for q in range(4):
            b.add(t0 + q * beat, _kick(), gain=0.6)
            if q in (1, 3):
                b.add(t0 + q * beat, _snare(bar * 4 + q), gain=0.35)
    b.scale_rms(-20)
    return b


def music_silly() -> Buf:
    bpm, bars = 128, 8
    beat = 60 / bpm
    b = Buf(bars * 4 * beat, loop=True)
    melody = [72, 76, 79, 76, 74, 77, 81, 77, 72, 76, 79, 84, 83, 79, 74, 71]
    for bar in range(bars):
        t0 = bar * 4 * beat
        for k in range(8):  # pizzicato-like plucks
            m = melody[(bar * 8 + k) % len(melody)]
            pn = int(0.2 * SR)
            b.add(t0 + k * beat / 2, mul(osc(midi(m), pn, "tri"), env_exp(pn, 0.06)), pan=0.2, gain=0.22)
        for q in range(4):  # oom-pah bass
            bn = int(0.25 * SR)
            root = 48 if bar % 2 == 0 else 43
            b.add(t0 + q * beat, mul(osc(midi(root if q % 2 == 0 else root + 7), bn, "tri"), env_exp(bn, 0.1)),
                  gain=0.35)
            if q % 2:
                b.add(t0 + q * beat, _hat(bar * 4 + q, open_=True), gain=0.08, pan=-0.3)
    b.scale_rms(-20)
    return b


