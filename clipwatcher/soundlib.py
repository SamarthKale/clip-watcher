def sfx_whoosh(dur: float, seed: int) -> Buf:
    n = int(dur * SR)
    b = Buf(dur + 0.05)
    peak = 0.55
    cut = lambda i: 250 + 7000 * math.sin(math.pi * min(1, i / n)) ** 2  # noqa: E731
    x = lowpass(noise(n, seed), cut, 2)
    x = highpass(x, 150)
    e = [math.sin(math.pi * min(1.0, i / n)) ** 1.5 * (1 + 0.6 * (i / n < peak)) for i in range(n)]
    x = mul(x, e)
    half = n // 2
    b.add(0, x[:half], pan=-0.6)
    b.add(half / SR, x[half:], pan=0.6)
    b.add(0, x, pan=0, gain=0.6)
    b.normalize(-1)
    return b


def sfx_impact() -> Buf:
    dur = 1.8
    n = int(dur * SR)
    b = Buf(dur)
    body = mul(osc(lambda i: 38 + 90 * math.exp(-i / (0.06 * SR)), n), env_exp(n, 0.5))
    click = mul(lowpass(noise(int(0.03 * SR), 7), 3000), env_exp(int(0.03 * SR), 0.008))
    tail = mul(lowpass(noise(n, 9), 400), env_exp(n, 0.25))
    b.add(0, drive(body, 2.5), gain=1.0)
    b.add(0, click, gain=0.8)
    b.add(0, tail, gain=0.25)
    b.normalize(-1)
    return b


