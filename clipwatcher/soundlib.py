"""Original, royalty-free sound library for Shorts editing.

`python -m clipwatcher make-assets` synthesizes sound effects and loopable
music beds from scratch (pure Python, no samples), so every sound in the
starter library is original work that is safe to use on YouTube (CC0).

You can add your own licensed audio (e.g. tracks from the YouTube Audio
Library) to assets/music/ or assets/sfx/. Running make-assets again lists them
in assets/library.json with license "UNKNOWN"; fill in the license and credit
there. The editor only uses entries with a known license, and credits any
track whose entry has a `credit`.
"""
