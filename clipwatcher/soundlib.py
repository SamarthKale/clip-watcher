def sfx_glitch() -> Buf:
    dur = 0.6
    b = Buf(dur)
    r = _rng(5)
    t = 0.0
    while t < dur - 0.03:
        seg = r.uniform(0.02, 0.07)
        n = int(seg * SR)
        x = osc(r.choice([110, 220, 330, 880, 1760, 2640]), n, r.choice(["square", "saw"]))
        step = r.choice([4, 8, 16])
        x = [x[i - i % step] for i in range(n)]  # sample-and-hold "bitcrush"
        b.add(t, x, pan=r.uniform(-0.8, 0.8), gain=r.uniform(0.3, 0.8))
        t += seg + r.uniform(0, 0.02)
    b.normalize(-2)
    return b


