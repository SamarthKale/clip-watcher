# --------------------------------------------------------------- library
def _wav_duration(path: Path) -> float | None:
    try:
        with wave.open(str(path), "rb") as w:
            return round(w.getnframes() / w.getframerate(), 3)
    except (wave.Error, OSError, EOFError):
        return None


def load_library(path: Path = LIBRARY) -> dict:
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"version": 1, "items": []}


def usable_items(lib: dict) -> list[dict]:
    return [it for it in lib.get("items", [])
            if it.get("license") and not str(it["license"]).upper().startswith(UNKNOWN)]


def make_assets(force: bool = False, log=print) -> dict:
    lib = load_library()
    items = {it["id"]: it for it in lib.get("items", [])}
    for kind, table in (("sfx", SFX), ("music", MUSIC)):
        for name, (fn, tags, use) in table.items():
            rel = f"{kind}/{name}.wav"
            path = ASSETS_DIR / rel
            if force or not path.exists():
                log(f"generating {rel}")
                buf = fn()
                if kind == "sfx":
                    buf.scale_rms(-18)  # level-match effects so default mix gains are predictable
                buf.write(path)
            items[f"{kind}/{name}"] = {
                "id": f"{kind}/{name}", "file": rel, "type": kind, "tags": tags, "use": use,
                "duration": _wav_duration(path), "loop": kind == "music",
                "level": "-18 dB RMS (peak <= -1 dBFS)" if kind == "sfx" else "-20 dB RMS",
                "license": GENERATED_LICENSE, "credit": "", "generated": True,
            }
    # Pick up audio the user dropped into assets/ themselves.
    for kind in ("sfx", "music"):
        for path in sorted((ASSETS_DIR / kind).glob("*")):
            if path.suffix.lower() not in (".wav", ".mp3", ".m4a", ".flac", ".ogg", ".aac"):
                continue
            rel = f"{kind}/{path.name}"
            iid = f"{kind}/{path.stem}"
            if iid in items:
                continue
            log(f"found user audio {rel} - set its license in assets/library.json before it can be used")
            items[iid] = {"id": iid, "file": rel, "type": kind, "tags": [], "use": "",
                          "duration": _wav_duration(path), "loop": kind == "music",
                          "license": f"{UNKNOWN} - fill in (e.g. 'YouTube Audio Library - no attribution')",
                          "credit": "", "generated": False}
    lib = {"version": 1,
           "note": "Only items with a known license are used. 'credit' text is added to Short descriptions.",
           "items": sorted(items.values(), key=lambda it: it["id"])}
    LIBRARY.parent.mkdir(parents=True, exist_ok=True)
    LIBRARY.write_text(json.dumps(lib, indent=2, ensure_ascii=False), encoding="utf-8")
    return lib
