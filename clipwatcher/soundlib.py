    tone = lowpass(tone, lambda i: 600 + 5000 * (i / n))
    e = [(i / n) ** 2.2 for i in range(n)]
    b.add(0, mul(nz, e), pan=-0.3)
    b.add(0, mul(tone, e), pan=0.3, gain=0.5)
    b.normalize(-1)
    return b


