# ------------------------------------------------------------- primitives
class Buf:
    """Stereo float buffer. `loop=True` wraps writes past the end to the start
    so release tails make a seamless loop."""

    def __init__(self, seconds: float, loop: bool = False):
        self.n = int(seconds * SR)
        self.l = [0.0] * self.n
        self.r = [0.0] * self.n
        self.loop = loop

    def add(self, start: float, samples: list[float], pan: float = 0.0, gain: float = 1.0) -> None:
        gl = gain * math.cos((pan + 1) * math.pi / 4)
        gr = gain * math.sin((pan + 1) * math.pi / 4)
        i0 = int(start * SR)
        n = self.n
        for k, s in enumerate(samples):
            i = i0 + k
            if i >= n:
                if not self.loop:
                    break
                i %= n
            self.l[i] += s * gl
            self.r[i] += s * gr

    def normalize(self, peak_db: float = -1.0) -> None:
        # soft-clip then normalize
        peak = max(1e-9, max(max(map(abs, self.l)), max(map(abs, self.r))))
        g = 10 ** (peak_db / 20) / peak
        self.l = [x * g for x in self.l]
        self.r = [x * g for x in self.r]

    def scale_rms(self, rms_db: float) -> None:
        """Set overall RMS level (used for music beds so they sit at a known loudness)."""
        tot = sum(x * x for x in self.l) + sum(x * x for x in self.r)
        rms = math.sqrt(tot / (2 * self.n)) or 1e-9
        g = 10 ** (rms_db / 20) / rms
        self.l = [x * g for x in self.l]
        self.r = [x * g for x in self.r]
        peak = max(max(map(abs, self.l)), max(map(abs, self.r)))
        if peak > 0.89:  # never above -1 dBFS
            c = 0.89 / peak
            self.l = [x * c for x in self.l]
            self.r = [x * c for x in self.r]

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        frames = bytearray()
        for a, b in zip(self.l, self.r):
            frames += struct.pack("<hh", int(max(-1, min(1, a)) * 32767), int(max(-1, min(1, b)) * 32767))
        with wave.open(str(path), "wb") as w:
            w.setnchannels(2)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes(bytes(frames))


def _rng(seed: int) -> random.Random:
    return random.Random(seed)


def noise(n: int, seed: int = 1) -> list[float]:
    r = _rng(seed)
    return [r.uniform(-1, 1) for _ in range(n)]


def lowpass(x: list[float], cutoff, q_stages: int = 1) -> list[float]:
    """One-pole lowpass; `cutoff` is Hz or a function of sample index."""
    out = x
    for _ in range(q_stages):
        y, res = 0.0, []
        for i, s in enumerate(out):
            fc = cutoff(i) if callable(cutoff) else cutoff
            a = 1 - math.exp(-2 * math.pi * max(10.0, fc) / SR)
            y += a * (s - y)
            res.append(y)
        out = res
    return out


def highpass(x: list[float], cutoff: float) -> list[float]:
    lp = lowpass(x, cutoff)
    return [a - b for a, b in zip(x, lp)]


def osc(freq, n: int, shape: str = "sine", phase: float = 0.0) -> list[float]:
    """Oscillator; `freq` is Hz or a function of sample index (for sweeps)."""
    out, ph = [], phase
    for i in range(n):
        f = freq(i) if callable(freq) else freq
        ph += f / SR
        p = ph % 1.0
        if shape == "sine":
            v = math.sin(2 * math.pi * p)
        elif shape == "tri":
            v = 4 * abs(p - 0.5) - 1
        elif shape == "saw":
            v = 2 * p - 1
        else:  # square
            v = 1.0 if p < 0.5 else -1.0
        out.append(v)
    return out


def env_adsr(n: int, a: float, d: float, s: float, r: float) -> list[float]:
    na, nd, nr = int(a * SR), int(d * SR), int(r * SR)
    out = []
    for i in range(n):
        if i < na:
            v = i / max(1, na)
        elif i < na + nd:
            v = 1 - (1 - s) * (i - na) / max(1, nd)
        else:
            v = s
        if i > n - nr:
            v *= max(0.0, (n - i) / max(1, nr))
        out.append(v)
    return out


def env_exp(n: int, tau: float, attack: float = 0.002) -> list[float]:
    na = max(1, int(attack * SR))
    return [(i / na if i < na else 1.0) * math.exp(-i / (tau * SR)) for i in range(n)]


def mul(a: list[float], b: list[float]) -> list[float]:
    return [x * y for x, y in zip(a, b)]


def drive(x: list[float], k: float = 2.0) -> list[float]:
    t = math.tanh(k)
    return [math.tanh(k * s) / t for s in x]


def midi(n: float) -> float:
    return 440.0 * 2 ** ((n - 69) / 12)


